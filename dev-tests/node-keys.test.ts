// ノードの鍵（ノード鍵・ハーベスト鍵・VRF 鍵・投票鍵）の、ウォレット側への連携: 公開鍵だけを読むこと、秘密鍵が出ないこと、
// エージェントの /v1/node-keys（認証・シンボリックリンク・tools/ の除外）、画面側の受け取り（再検証）、渡し先のストアを確かめる。
// 実行: npx tsx dev-tests/node-keys.test.ts
import { mkdtempSync, rmSync, mkdirSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import type { AddressInfo } from 'node:net';
import { createAgent } from '../src/server/node-agent/agent';
import { fetchNodeKeys, AgentError } from '../src/lib/node/agentClient';
import { parseAddressesYml, sanitizeNodeKeySets } from '../src/lib/node/nodeKeys';
import { useNodeKeysStore } from '../src/store/nodeKeysStore';

let fails = 0, checks = 0;
function ok(cond: boolean, what: string, extra?: unknown) { checks++; if (!cond) { fails++; console.log('FAIL:', what, extra ?? ''); } }

const hex = (c: string, n: number) => c.repeat(n);
const PUB = { main: hex('1A', 32), transport: hex('2B', 32), remote: hex('3C', 32), vrf: hex('4D', 32) };
const PRIV = { main: hex('A1', 32), transport: hex('B2', 32), remote: hex('C3', 32), vrf: hex('D4', 32) };
const VOTING = hex('5E', 32); // 64 文字（32 バイト。symbol-sdk の VotingPublicKey）
const PRIV_ALL = Object.values(PRIV);

const account = (ind: string, pub: string, priv: string, extra = '') =>
  `${ind}address: TABCDEFGHIJKLMNOPQRSTUVWXYZ234567ABCDEFG\n${ind}publicKey: ${pub}\n${ind}privateKey: ${priv}\n${extra}`;

const YML = `# generated by symbol-bootstrap
nodes:
  - name: node
    main:
${account('      ', PUB.main, PRIV.main)}    transport:
${account('      ', PUB.transport, PRIV.transport)}    remote:
${account('      ', PUB.remote, PRIV.remote)}    vrf:
${account('      ', PUB.vrf, PRIV.vrf)}  - name: "second"
    main:
      publicKey: '${hex('0F', 32)}'
      privateKey: ${hex('F1', 32)}
    remote:
      publicKey: ${hex('77', 32)} # comment
      privateKey: ${hex('F2', 32)}
nemesisSigner:
  address: TXXXX
  publicKey: ${hex('99', 32)}
  privateKey: ${hex('F3', 32)}
`;

// --- parseAddressesYml
{
  const sets = parseAddressesYml(YML);
  ok(sets.length === 2, 'two nodes', sets);
  ok(sets[0].name === 'node' && sets[0].main === PUB.main && sets[0].node === PUB.transport && sets[0].remote === PUB.remote && sets[0].vrf === PUB.vrf, 'node 1: main/transport(node)/remote/vrf public keys', sets[0]);
  ok(sets[0].voting === null, 'no voting key in the file → null');
  ok(sets[1].name === 'second' && sets[1].main === hex('0F', 32) && sets[1].remote === hex('77', 32) && sets[1].node === null && sets[1].vrf === null, 'node 2: quoted value, trailing comment, missing sections', sets[1]);
  ok(!JSON.stringify(sets).includes(hex('99', 32)), 'a publicKey outside nodes: (nemesisSigner) is not taken');
  const json = JSON.stringify(sets).toUpperCase();
  ok(PRIV_ALL.every((p) => !json.includes(p.toUpperCase())) && !json.includes(hex('F1', 32)) && !json.includes(hex('F2', 32)), 'no private key value is in the result');
  ok(!json.includes('PRIVATEKEY'), 'the result has no privateKey field');
}
{
  // 小文字は大文字にそろえる。長さの違う値は捨てる。CRLF。
  const lower = `nodes:\r\n  - name: a\r\n    transport:\r\n      publicKey: ${hex('ab', 32)}\r\n    remote:\r\n      publicKey: ${hex('cd', 31)}\r\n    vrf:\r\n      publicKey: ${hex('zz', 32)}\r\n`;
  const [s] = parseAddressesYml(lower);
  ok(s.node === hex('AB', 32), 'lower case is upper-cased (CRLF ok)', s);
  ok(s.remote === null && s.vrf === null, 'wrong length / non-hex values are dropped', s);
  // 投票鍵は 64 文字（32 バイト）のときだけ。96 文字（BLS の大きさ）は、symbol-sdk が書き込めないので受け取らない
  const v = `nodes:\n  - name: v\n    voting:\n      publicKey: ${VOTING}\n`;
  ok(parseAddressesYml(v)[0].voting === VOTING.toUpperCase(), 'voting key (64 hex) is read when the file has one');
  const v96 = `nodes:\n  - name: v\n    voting:\n      publicKey: ${hex('11', 48)}\n`;
  ok(parseAddressesYml(v96)[0].voting === null, 'a 96-char value is not a voting key');
  // 節の外の publicKey は、取らない（remote の後ろ、別のキーの下）
  const stray = `nodes:\n  - name: s\n    remote:\n      publicKey: ${hex('33', 32)}\n    other:\n      publicKey: ${hex('44', 32)}\n`;
  const [st] = parseAddressesYml(stray);
  ok(st.remote === hex('33', 32) && st.vrf === null && st.node === null && st.main === null, 'a publicKey under an unknown section is not taken', st);
  ok(parseAddressesYml('').length === 0 && parseAddressesYml('foo: bar\n').length === 0 && parseAddressesYml('nodes:\n').length === 0, 'empty / unrelated text → no nodes');
  // 名前を次の行に書く形、名前なし
  ok(parseAddressesYml(`nodes:\n  -\n    name: late\n    vrf:\n      publicKey: ${hex('55', 32)}\n`)[0]?.name === 'late', 'name on the line after the dash');
  // ハイフンが 0 字下げ
  ok(parseAddressesYml(`nodes:\n- name: flat\n  remote:\n    publicKey: ${hex('66', 32)}\n`)[0]?.remote === hex('66', 32), 'list items at column 0');
}

// --- sanitizeNodeKeySets（画面は、エージェントの返事を信用しない）
{
  const raw = [
    { name: 'n', source: 'target/addresses.yml', main: PUB.main.toLowerCase(), node: 'short', remote: PUB.remote, vrf: 12, voting: VOTING, privateKey: PRIV.remote, extra: 'x' },
    'junk', null, 5,
  ];
  const out = sanitizeNodeKeySets(raw);
  ok(out.length === 1 && out[0].main === PUB.main && out[0].node === null && out[0].vrf === null && out[0].voting === VOTING, 'validated and upper-cased; bad values dropped', out);
  ok(!JSON.stringify(out).includes('privateKey') && !JSON.stringify(out).includes(PRIV.remote), 'unknown fields (even privateKey) are dropped');
  ok(sanitizeNodeKeySets('x').length === 0 && sanitizeNodeKeySets(undefined).length === 0, 'non-array → []');
  ok(sanitizeNodeKeySets(Array.from({ length: 80 }, () => ({}))).length === 50, 'at most 50 entries');
}

// --- 渡し先のストア
{
  const st = useNodeKeysStore;
  st.getState().clear();
  ok(st.getState().pending === null, 'store starts empty');
  st.getState().set({ node: 'bad', remote: PUB.remote.toLowerCase(), vrf: null, voting: hex('4D', 48) });
  const p = st.getState().pending;
  ok(p !== null && p.node === null && p.remote === PUB.remote && p.vrf === null && p.voting === null, 'store keeps only well-formed keys (voting needs 64 hex; 96 is refused)', p);
  st.getState().set({ node: 'bad' });
  ok(st.getState().pending === null, 'nothing valid → nothing is stored');
  st.getState().set({ voting: VOTING.toLowerCase() });
  ok(st.getState().pending?.voting === VOTING.toUpperCase(), 'voting key is accepted at 64 hex');
  st.getState().clear();
  ok(st.getState().pending === null, 'clear empties it');
}

// --- エージェントの /v1/node-keys
const TOKEN = 'b'.repeat(64);
const ws = mkdtempSync(join(tmpdir(), 'irome-keys-'));
const outside = mkdtempSync(join(tmpdir(), 'irome-keys-out-'));
const agent = createAgent({ token: TOKEN, workspace: ws, origins: ['null'] });

async function main() {
  await new Promise<void>((r) => agent.server.listen(0, '127.0.0.1', r));
  const port = (agent.server.address() as AddressInfo).port;
  const conn = { url: `http://127.0.0.1:${port}`, token: TOKEN };
  const raw = (path: string, headers: Record<string, string>) => fetch(`${conn.url}${path}`, { headers });

  // 何も無いとき
  ok((await fetchNodeKeys(conn)).length === 0, 'no target/addresses.yml → []');

  mkdirSync(join(ws, 'target'), { recursive: true });
  writeFileSync(join(ws, 'target', 'addresses.yml'), YML);
  mkdirSync(join(ws, 'mainnet', 'target'), { recursive: true });
  writeFileSync(join(ws, 'mainnet', 'target', 'addresses.yml'), `nodes:\n  - name: mn\n    vrf:\n      publicKey: ${hex('88', 32)}\n    voting:\n      publicKey: ${VOTING}\n`);
  // 読んではいけないもの: tools/ の中、シンボリックリンク、target/ の外の addresses.yml、node_modules、隠しフォルダ
  mkdirSync(join(ws, 'tools', 'x', 'target'), { recursive: true });
  writeFileSync(join(ws, 'tools', 'x', 'target', 'addresses.yml'), `nodes:\n  - name: tools\n    vrf:\n      publicKey: ${hex('AA', 32)}\n`);
  writeFileSync(join(ws, 'addresses.yml'), `nodes:\n  - name: notarget\n    vrf:\n      publicKey: ${hex('BB', 32)}\n`);
  mkdirSync(join(outside, 'target'), { recursive: true });
  writeFileSync(join(outside, 'target', 'addresses.yml'), `nodes:\n  - name: outside\n    vrf:\n      publicKey: ${hex('CC', 32)}\n`);
  symlinkSync(outside, join(ws, 'linked'));
  mkdirSync(join(ws, '.hidden', 'target'), { recursive: true });
  writeFileSync(join(ws, '.hidden', 'target', 'addresses.yml'), `nodes:\n  - name: hidden\n    vrf:\n      publicKey: ${hex('DD', 32)}\n`);

  const keys = await fetchNodeKeys(conn);
  const names = keys.map((k) => k.name).sort();
  ok(names.join(',') === 'mn,node,second', 'reads target/addresses.yml at the top and in a sub folder, nothing else', names);
  const first = keys.find((k) => k.name === 'node');
  ok(first?.source === 'target/addresses.yml' && first.node === PUB.transport && first.remote === PUB.remote && first.vrf === PUB.vrf && first.main === PUB.main, 'keys and source path', first);
  ok(keys.find((k) => k.name === 'mn')?.voting === VOTING, 'voting key of a sub-folder file', keys);

  // 返事の本文に、秘密鍵の値が1つも出ない（エージェントの返事そのものを見る）
  const res = await raw('/v1/node-keys', { Authorization: `Bearer ${TOKEN}` });
  const text = (await res.text()).toUpperCase();
  ok(res.status === 200, 'node-keys → 200', res.status);
  ok(PRIV_ALL.every((p) => !text.includes(p.toUpperCase())) && !text.includes(hex('F1', 32)) && !text.includes('PRIVATEKEY'), 'the agent response holds no private key');

  // 認証・Origin
  ok((await raw('/v1/node-keys', {})).status === 401, 'node-keys needs the token');
  ok((await raw('/v1/node-keys', { Authorization: 'Bearer nope' })).status === 401, 'node-keys: wrong token → 401');
  ok((await raw('/v1/node-keys', { Authorization: `Bearer ${TOKEN}`, Origin: 'https://evil.example' })).status === 403, 'node-keys: foreign origin → 403');
  const bad = await fetchNodeKeys({ url: conn.url, token: 'x' }).catch((e) => e);
  ok(bad instanceof AgentError && bad.kind === 'unauthorized', 'client: unauthorized', bad);

  // 大きすぎるファイルは読まない
  writeFileSync(join(ws, 'target', 'addresses.yml'), `nodes:\n  - name: big\n${'#'.repeat(300_000)}\n    vrf:\n      publicKey: ${hex('EE', 32)}\n`);
  ok(!(await fetchNodeKeys(conn)).some((k) => k.name === 'big'), 'a file over the size limit is skipped');

  agent.server.close();
  rmSync(ws, { recursive: true, force: true });
  rmSync(outside, { recursive: true, force: true });
  console.log(`${checks} checks, ${fails} failed`);
  process.exit(fails === 0 ? 0 : 1);
}
main().catch((e) => { console.error(e); process.exit(1); });
